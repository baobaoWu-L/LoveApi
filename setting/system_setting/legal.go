var defaultLegalSettings = LegalSettings{
	UserAgreement: DefaultUserAgreement,
	PrivacyPolicy: DefaultPrivacyPolicy,
}

func init() {
	config.GlobalConfig.Register("legal", &defaultLegalSettings)
}

func GetLegalSettings() *LegalSettings {
	if defaultLegalSettings.UserAgreement == "" {
		defaultLegalSettings.UserAgreement = DefaultUserAgreement
	}
	if defaultLegalSettings.PrivacyPolicy == "" {
		defaultLegalSettings.PrivacyPolicy = DefaultPrivacyPolicy
	}
	return &defaultLegalSettings
}
